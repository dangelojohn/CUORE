"""Regenerates the "Which cable for which module" section of
docs/handbook/07-first-live-session.md.

Pure presentation over ``cuore.web.fullscan_routes.cable_reference_table()``
-- the exact same function the Full scan wizard page
(``/v/{vin}/scan``) calls to render its own on-screen reference (idle
screen and every pause card). That function is itself generated from
``cuore.live.buses`` (cable/bus pairing, bitrate -> HS/MS adapter switch)
and ``cuore.live.ops.modules()`` (the module list and each module's
confidence chip, which reads the ``addressing.MODULES`` registry).

Nothing in this script is hand-typed data about modules, buses, cables or
confidence -- only Markdown formatting. Re-run it after any change to
``cuore/live/addressing.py`` or ``cuore/live/buses.py`` so the handbook
section can never drift from the registry or from the wizard page that
reads the same function.

Run:
    .venv/Scripts/python.exe docs/handbook/generate_cable_reference.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from cuore.web.fullscan_routes import cable_reference_table  # noqa: E402

START = ("<!-- cable-reference:start (generated by "
         "docs/handbook/generate_cable_reference.py -- do not hand-edit "
         "between these markers; re-run the script instead) -->")
END = "<!-- cable-reference:end -->"


def render_block() -> str:
    lines = [
        START,
        "",
        "## 8. Which cable for which module",
        "",
        "Generated straight from the live module registry (`cuore/live/buses.py` "
        "+ `cuore.live.ops.modules()`) by `docs/handbook/generate_cable_reference.py` "
        "-- never hand-typed. This is the same table the Full scan wizard "
        "(`/v/{vin}/scan`) shows on its idle screen and on every pause card, so "
        "the page and this section can never disagree with each other or with "
        "the registry both are drawn from. Re-run the script after any change "
        "to `addressing.py` or `buses.py`.",
        "",
    ]
    for col in cable_reference_table():
        lines.append(
            f"### {col['cable_label']} ({col['bus_label']}) -- adapter switch: {col['switch']}"
        )
        lines.append("")
        lines.append("| Module | Confidence |")
        lines.append("|---|---|")
        for m in col["modules"]:
            lines.append(f"| {m['code']} | {m['confidence']} |")
        lines.append("")
    lines.append(END)
    return "\n".join(lines) + "\n"


def apply(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    block = render_block()
    if START in text and END in text:
        pre = text.split(START, 1)[0]
        post = text.split(END, 1)[1]
        new_text = pre + block + post
    else:
        new_text = text.rstrip() + "\n\n" + block
    path.write_text(new_text, encoding="utf-8")
    return new_text


if __name__ == "__main__":
    target = Path(__file__).resolve().parent / "07-first-live-session.md"
    apply(target)
    print(f"wrote {target}")

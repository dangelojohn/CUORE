"""Guards ``docs/mobile/API_CONTRACT.md`` against drift.

That document is the contract a native iPhone app (Swift or Flutter) talks
to in place of the phone web page ``/m/{vin}``. It was generated by reading
``app.openapi()`` once; this check re-reads ``app.openapi()`` on every run
and fails if any ``(method, path)`` row in the doc's own "Path table" is no
longer present in the live schema -- the one way a doc like this silently
goes stale is someone renaming or removing a route without knowing a mobile
client depends on it.

This does not attempt to fail on *additions* (a new route showing up in the
schema that the doc does not yet mention) -- only disappearance of a
documented one, which is the breaking case for a client already built
against this contract.

Same posture as every other ``check_*.py`` here: plain script, ``check()``,
exit 1 on failure, no pytest. ``CUORE_STATE_DIR`` is pointed at a throwaway
directory before ``cuore`` is imported, so this needs no real corpus.

Run:
    .venv/Scripts/python.exe cuore/tests/check_api_contract.py
"""

from __future__ import annotations

import os
import re
import sys
import tempfile
from pathlib import Path

# Before any cuore import: state goes to a throwaway directory.
os.environ["CUORE_STATE_DIR"] = tempfile.mkdtemp(prefix="cuore-check-apicontract-")

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from cuore.app import create_app  # noqa: E402

DOC_PATH = Path(__file__).resolve().parents[2] / "docs" / "mobile" / "API_CONTRACT.md"

#: Matches one row of the doc's "| Method | Path | Summary |" table, e.g.
#: "| POST | /api/owner/{vin}/events | Record one owner-reported event |".
#: Anchored on a leading HTTP verb so the table's own header/separator rows
#: (``| Method | Path | Summary |``, ``|---|---|---|``) never match.
ROW_RE = re.compile(
    r"^\|\s*(GET|POST|PUT|PATCH|DELETE)\s*\|\s*(/api/\S+?)\s*\|", re.MULTILINE)

failures: list[str] = []
checks = 0


def check(label: str, condition: bool, detail: str = "") -> None:
    global checks
    checks += 1
    if not condition:
        failures.append(f"{label}{(' -- ' + detail) if detail else ''}")


# --- load the doc's own path table -----------------------------------------

check(f"{DOC_PATH} exists", DOC_PATH.exists())
text = DOC_PATH.read_text(encoding="utf-8")

rows = ROW_RE.findall(text)
check("the doc's path table has rows", len(rows) > 0)
check("the doc's path table has a non-trivial number of rows",
      len(rows) >= 10, f"found {len(rows)}")

# --- compare against the live schema ----------------------------------------

app = create_app()
spec = app.openapi()
paths = spec["paths"]

for method, doc_path in rows:
    entry = paths.get(doc_path)
    check(f"{doc_path} is still in app.openapi()", entry is not None,
          f"documented in API_CONTRACT.md as {method} {doc_path}, not found "
          "in the live schema -- update or remove that row, and tell "
          "whoever owns the mobile client")
    if entry is not None:
        check(f"{method} {doc_path} is still a method on that path",
              method.lower() in entry,
              f"path exists but no longer supports {method}")

# A sanity floor on specific routes the doc leans on hardest, named
# explicitly so a future refactor that breaks one of these fails loudly
# here rather than only as a generic "row not found" above.
for method, must_have in (
    ("get", "/api/health"),
    ("get", "/api/capabilities"),
    ("get", "/api/vehicle/{vin}/report"),
    ("get", "/api/owner/{vin}/taxonomy"),
    ("post", "/api/owner/{vin}/events"),
    ("post", "/api/vehicles/{vin}/media"),
    ("get", "/api/vision/status"),
    ("post", "/api/vision/{vin}/read"),
):
    check(f"core mobile route {method.upper()} {must_have} exists",
          must_have in paths and method in paths[must_have])

# The doc's "fields_meta provenance" gap note is only true as long as
# OwnerEventRequest has no such property -- flag it loudly (not a hard
# failure list the doc can't react to) the day that changes, since the doc
# then needs a rewrite, not just a row update.
owner_event_schema = spec.get("components", {}).get("schemas", {}).get(
    "OwnerEventRequest", {})
has_fields_meta = "fields_meta" in owner_event_schema.get("properties", {})
check("OwnerEventRequest still has no fields_meta property (doc's vision "
      "gap note is current -- if this now fails, update "
      "docs/mobile/API_CONTRACT.md's 'fields_meta provenance' section, it "
      "is now stale)",
      not has_fields_meta)


print(f"checks run: {checks}")
if failures:
    print(f"FAILURES: {len(failures)}")
    for f in failures:
        print("  -", f)
    sys.exit(1)
print("all green")
